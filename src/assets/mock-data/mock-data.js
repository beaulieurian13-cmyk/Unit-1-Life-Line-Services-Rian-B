// About Me
// My Story

// Lifeline Services was created from a deeply personal experience. I know firsthand what it is like to live with PTSD and how much it can affect your everyday life. There were times when having a trained service dog could have made my life easier—helping me feel safer, more independent, and more confident in situations that felt overwhelming.

// But there was a major obstacle: I could not afford a service dog.

// Knowing that something that could have made such a meaningful difference in my life was out of reach financially stayed with me. I began thinking about how many other people may be experiencing the same thing—people who need help, but cannot afford the cost of obtaining a properly trained service dog.

// I don't want anyone else to feel like they have to face that struggle alone.

// That is why I created Lifeline Services. My goal is to help make trained service dogs more accessible to people who truly need them and to provide support throughout the journey—not just when someone receives their dog, but as they learn, grow, and build a life together.

// A service dog is more than a trained animal. For the right person, they can become a source of independence, confidence, stability, and hope.

// Lifeline Services exists because I believe everyone who genuinely needs that lifeline deserves the opportunity to have one.

// Our Core Values
// Honesty

// We believe in being truthful and transparent with the people we serve. Trust is the foundation of everything we do.

// Helping Others

// At the heart of Lifeline Services is the desire to make a meaningful difference in people's lives and remind them that they do not have to face everything alone.

// Integrity

// We will do what is right, even when it is difficult. We hold ourselves accountable to the people, families, trainers, and animals who depend on us.

// Commitment

// Helping someone receive and successfully work with a service dog is a long-term commitment. We are dedicated to supporting our clients throughout their journey.

// Compassion

// Everyone's story is different. We believe people deserve to be treated with patience, understanding, dignity, and respect.

// Empowerment

// Our goal is not simply to provide a service dog. We want to help people regain confidence, independence, and the ability to move forward with their lives.

// Respect

// We respect every individual we serve, their experiences, their needs, and their goals. We also believe in treating every dog with kindness and respect.

// Our Future Goals
// 1. Create Our Own Training Facility

// Our long-term goal is to establish a dedicated Lifeline Services facility where service dogs can be trained, cared for, and prepared for their future roles.

// 2. Provide On-Site Dog Housing

// We want our facility to include safe, comfortable spaces where dogs can stay while receiving their training and care.

// 3. Create a Training Stay for Clients

// We hope to provide a place where potential service-dog owners can stay while learning how to work with their dog. This would allow clients to receive hands-on training in a supportive environment before returning home.

// 4. Expand Access to Service Dogs

// We want to help more people who need service dogs but may not have the financial resources to obtain one through traditional programs.

// 5. Build a Lifelong Support Program

// Receiving a service dog should not be the end of the journey. We want to provide ongoing education, training resources, communication with staff and trainers, and support when challenges arise.

// 6. Build a Community of Support

// Our ultimate goal is to create a community where service-dog recipients, trainers, volunteers, and supporters can come together to share knowledge, encouragement, and resources.

// Our Vision

// Lifeline Services is more than a program to connect people with service dogs. It is a mission built from personal experience and the belief that no one should have to struggle alone simply because they cannot afford the help they need.

// Our vision is to create a future where a person's financial situation does not prevent them from having the opportunity to gain greater independence, confidence, and hope through a properly trained service dog.




